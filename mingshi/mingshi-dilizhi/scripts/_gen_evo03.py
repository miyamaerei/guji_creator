from collections import OrderedDict

groups = OrderedDict()
for iid, era_raw, reign, yn, ct, chg, owner in D:
    groups.setdefault(iid, []).append((era_raw, reign, yn, ct, chg, owner))

out = []
slot = 0
for iid, items in groups.items():
    for ph, (era_raw, reign, yn, ct, chg, owner) in enumerate(items, start=1):
        slot += 1
        rec = {
            "slot": slot,
            "item_id": iid,
            "phase": ph,
            "era_raw": era_raw,
            "reign": reign,
            "change_type": ct,
            "change": chg,
            "owner": owner,
        }
        if isinstance(yn, int) and yn >= 1:
            rec["year"] = REIGN_START[reign] + yn - 1
        out.append(rec)

