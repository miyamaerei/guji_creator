# ===== 记录 schema（与现有 _src 一致）=====
#
# NAM 名录记录：
# {
#   "id": "<唯一ID>",
#   "item_id": "NNN-NNN",            # 必须是 registry 中存在且当前未覆盖的条目
#   "name": "<名称>",                 # 名录标题/名物串，照抄原文 title
#   "nam_type": "<NAM_TYPE 之一>",
#   "scope": "<六部/宗人府/院寺等>",
#   "entries": []                     # 可空数组；卷108样板即用空 entries
# }
#
# 人员配置 NAM（仅当条目内容是 司吏/典吏/攒典 等编制数时）：
# {
#   "id": "...", "item_id": "...", "name": "<衙门>·人员配置",
#   "nam_type": "人员配置", "scope": "...",
#   "staff_config": [{"role": "<STAFF_ROLE 之一>", "count": "一名/二名..."}]
# }
#
# RUL 规则记录：
# {
#   "id": "<唯一ID>",
#   "item_id": "NNN-NNN",
#   "type": "<RUL_TYPE 之一>",
#   "source_marker": "<SOURCE_MARKER 之一>",
#   "subject": "<主语>", "action": "<动作>",
#   "condition": "<条件可空>", "purpose": "<事由可空>",
#   "confidence": 0.9
# }

# ===== 枚举封闭集（改值=registerVersion+1，禁止新增）=====
RUL_TYPE = ["禁止", "义务", "允许", "程序", "时限", "处罚", "优先级"]
SOURCE_MARKER = ["诏", "敕", "奏准", "议准", "奏定", "议定", "令", "凡"]
NAM_TYPE = ["王府拟名", "卫所名录", "驿递名录", "仓场名录", "寺观名录",
            "官职题名", "官制名录", "人员配置", "封爵名录", "其他"]
STAFF_ROLE = ["提控", "都吏", "掾史", "令史", "司吏", "典吏",
              "攒典", "承发", "门吏", "狱典", "未明"]

# ===== 分类判定启发式（子进程据此逐条判定）=====
#
# 判定一个未覆盖条目走 NAM 还是 RUL：
#
# 走 RUL 的情况（title 或 original）：
#   1. 以"凡"开头                      -> source_marker="凡"
#   2. 以"国初置"/"国初"开头（沿革）    -> source_marker="凡", type="程序"
#   3. 年号+"令"（如"宣德三年令..."）   -> source_marker="令"
#   4. 含"奏准/议准/奏定/议定/诏/敕"     -> 对应 source_marker
#   5. 原文是一句完整的规定/程序/禁令
#   RUL.type 速查：
#     - 禁止性（不许/不得/毋/勿）       -> "禁止"
#     - 义务性（须/要/当/照例）         -> "义务"
#     - 程序/流程（怎么办理、班次）      -> "程序"
#     - 时限（限/即日/三日）            -> "时限"
#     - 处罚（笞/杖/发遣/治罪）         -> "处罚"
#     - 允许（许/听）                   -> "允许"
#     - 拿不准                          -> "义务"（最常见，占存量79%）
#
# 走 NAM 的情况：title 是短名/名单（不是完整句子）：
#   - 卫所/镇戍/都司/都督府/千户所 名   -> nam_type="卫所名录"
#   - 驿/递运所/驿程                    -> "驿递名录"
#   - 仓/场/库/税课司                   -> "仓场名录"
#   - 寺/观/庙/祠（神祇）               -> "寺观名录"
#   - 司吏/典吏/攒典/掾史 编制数        -> "人员配置"(带 staff_config)
#   - 官职题名/事目短标题（如"赏赐""提问军职"）-> "官制名录"
#   - 行政区划/图志（府州县/县N/领县N） -> "其他"
#   - 实在拿不准                         -> "其他"
#
# ===== OCR 归一（只在需要时）=====
#   "明防典"->"明会典"；"奉防"->"奉旨"。其余照抄原文，不强行纠字。
#
# ===== 输出与自检协议（子进程必须遵守）=====
# 1. 只写自己 tag 的源文件，文件名见各子任务；不要动别人的文件。
# 2. 不要运行 build_layers.py / validate_layers.py（并发会互相覆盖 _layers）。
# 3. 自检：load 自己生成的 RECORDS，逐条断言：
#      - item_id 在 _item_registry.json 中
#      - item_id 在开工时属于"未覆盖"集合（不与存量抢条目）
#      - RUL.type / source_marker 命中枚举；NAM.nam_type 命中枚举；
#        staff_config.role 命中 STAFF_ROLE
#    自检失败的值：不要硬塞，归入 _pending_enums.csv 并跳过该条（保证枚举错误=0）。
# 4. id 命名：NAM-<TAG>-<卷>-<序号> 或 RUL-<TAG>-<卷>-<序号>，保证全局唯一。
