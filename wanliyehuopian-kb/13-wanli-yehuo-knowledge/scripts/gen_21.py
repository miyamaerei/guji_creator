def pos(item, sub, nth=1):
    """返回原文中 sub 第 nth 次出现的 (start, end)（含【标题】在内计偏移）。"""
    t = texts[item]
    p = -1
    for _ in range(nth):
        p = t.find(sub, p + 1)
        assert p >= 0, f'NOT FOUND {item} {sub} #{nth}'
    return p, p + len(sub)

def find_src(item, sub):
    """source_text 精确取原文一句（截断至 32 字），找不到时报错。"""
    t = texts[item]
    assert sub in t, f'SRC NOT FOUND {item}: {sub[:12]}'
    return sub

