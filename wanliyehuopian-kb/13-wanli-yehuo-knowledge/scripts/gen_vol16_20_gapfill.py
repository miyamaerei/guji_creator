# ---------------------------------------------------------------- source text
parts = re.findall(r"●卷(十六|十七|十八|十九|二十)\n(.*?)(?=●卷|\Z)",
                   io.open(os.path.join(ROOT, "assets", "sources", "万历野获编.txt"), encoding="utf-8").read(), re.S)
body = {p[0]: p[1] for p in parts}
TEXTS = {}
for v, cn in VOLMAP.items():
    splits = re.split(r"【([^】]+)】", body[cn])
    seq = [(splits[i], re.sub(r"\s", "", splits[i + 1])) for i in range(1, len(splits), 2)]
    reg = [r for r in REGISTRY if r["volume"] == v]
    assert len(seq) == len(reg), v
    for (t, c), r in zip(seq, reg):
        assert t == r["entry_title"], (v, t, r["entry_title"])
        TEXTS[r["item_id"]] = c

def src(item):
    t = [r for r in REGISTRY if r["item_id"] == item][0]
    return "【%s】%s" % (t["entry_title"], TEXTS[item]), t

def span(item, text):
    full, _ = src(item)
    i = full.find(text)
    if i < 0:
        raise AssertionError("原文词形不在条目原文: %s %r" % (item, text))
    return i, i + len(text)

# ---------------------------------------------------------------- id allocator
POOL_START, POOL_END = 4600, 4799
pool_ptr = POOL_START
ENT_OF = {}  # (item, text) -> ent_id

class Seq:
    def __init__(self, layer, vol):
        keyf = {"ents": "ent_id", "rules": "rule_id", "events": "event_id", "appts": "appt_id",
                "rels": "rel_id", "cits": "cit_id", "opns": "opn_id", "mings": "ming_id",
                "tmes": "tme_id", "regs": "reg_id"}[layer]
        path = os.path.join(ROOT, "_layers", layer, "%s_%s.json" % (layer, vol))
        self.recs = json.load(io.open(path, encoding="utf-8"))
        assert isinstance(self.recs, list), path
        if layer == "ents":
            self.next = None  # ents 走全局池
        else:
            mx = max(int(r[keyf].rsplit("-", 1)[1]) for r in self.recs) if self.recs else 0
            self.next = mx + 1
        self.prefixes = {"rules": "RULE-", "events": "EVT-", "appts": "APPT-", "rels": "REL-",
                         "cits": "CIT-", "opns": "OPN-", "mings": "MING-", "tmes": "YHB-TME-",
                         "regs": "REG-"}[layer] if layer != "ents" else None
        self.keyf = keyf
        self.path = path

    def nid(self):
        n = self.next
        self.next += 1
        return "%s%s-%03d" % (self.prefixes, self._vol, n)

NEW = {}  # (layer, vol) -> appended record list

BAD = []
def _chk(cond, msg):
    if not cond:
        BAD.append(msg)

def add(layer, vol, rec):
    NEW.setdefault((layer, vol), []).append(rec)

# 先登记各卷各层起始号（ents 全局池另行）
