def load_item_originals():
    recs = json.load(open(BASE / "_item_registry.json", encoding="utf-8"))["records"]
    return {r["item_id"]: r["original"] for r in recs}


def align_ents(vol, recs, originals):
    """卷 09-10 的 ents 记录带 start/end/confidence/source 字段（与本卷旧记录一致）。"""
    out = []
    for r in recs:
        if vol in ("09", "10"):
            orig = originals.get(r["item_id"], "")
            idx = orig.find(r["text"])
            out.append({
                "ent_id": r["ent_id"], "item_id": r["item_id"], "text": r["text"],
                "type": r["type"], "normalized": r["normalized"],
                "start": idx if idx >= 0 else None,
                "end": idx + len(r["text"]) if idx >= 0 else None,
                "confidence": r["confidence"], "source": r["item_id"],
                "role_in_entry": r["role_in_entry"], "faction": r["faction"],
                "exam_info": r["exam_info"], "career_span": r["career_span"],
            })
        else:
            s = dict(r)
            s.pop("confidence", None)  # 卷06-08 旧记录不含该字段，保持同构
            out.append(s)
    return out


def main():
    originals = load_item_originals()
    report = {}
    for vol, layers in NEW.items():
        report[vol] = {}
        for layer, new_recs in layers.items():
            if layer == "ents":
                new_recs = align_ents(vol, new_recs, originals)
            path = LAYERS / layer / f"{layer}_{vol}.json"
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            wrapped = isinstance(data, dict)
            old_recs = data["records"] if wrapped else data
            assert VOLWRAP[vol] is dict if wrapped else VOLWRAP[vol] is list, (vol, layer)
            merged = old_recs + new_recs
            out = {"records": merged} if wrapped else merged
            with open(path, "w", encoding="utf-8") as f:
                json.dump(out, f, ensure_ascii=False, indent=2)
                f.write("\n")
            report[vol][layer] = len(new_recs)
    for vol in sorted(report):
        print(vol, json.dumps(report[vol], ensure_ascii=False))
    print("total new:", sum(sum(v.values()) for v in report.values()))


if __name__ == "__main__":
    main()
