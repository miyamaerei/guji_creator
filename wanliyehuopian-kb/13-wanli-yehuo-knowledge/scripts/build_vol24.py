def check_ids(rows, idkey, prefix, label):
    ids = [r[idkey] for r in rows]
    if len(ids) != len(set(ids)):
        errs.append('%s: 重复 ID' % label)
    for r in rows:
        if not r[idkey].startswith(prefix):
            errs.append('%s: ID 前缀错误 %s' % (label, r[idkey]))
        if len(r) < 8:
            errs.append('%s: 字段数不足 %s' % (label, r[idkey]))

