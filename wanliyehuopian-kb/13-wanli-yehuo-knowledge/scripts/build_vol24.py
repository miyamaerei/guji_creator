def dump(layer, data):
    d = os.path.join(LAYERS, layer)
    os.makedirs(d, exist_ok=True)
    p = os.path.join(d, '%s_24.json' % layer)
    tmp = p + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')
    if os.path.exists(p):
        os.remove(p)
    os.rename(tmp, p)
    return len(data)

