KEEP_TYPES = ("book", "artifact", "institution", "official", "custom", "religion",
              "event_name", "ethnic", "place")


def priority(e):
    k = e[0]
    if k in referenced:
        return 0
    if e[2] in KEEP_TYPES:
        return 1
    if "主体" in e[4]:
        return 2
    return 3


