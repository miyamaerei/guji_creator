valid_items = {f'31-{i:03d}' for i in range(1, 65)}
covered = set()
ent_ids = set()
data_by_layer = {}
for layer in LAYER_KEYS:
    p = os.path.join(LAYERS, layer, f'{layer}_{V}.json')
    with open(p, encoding='utf-8') as f:
        try:
            data = json.load(f)
        except Exception as e:
            errs.append(f'{layer}: JSON 解析失败 {e}')
            continue
    if not isinstance(data, list):
        errs.append(f'{layer}: 顶层不是数组')
        continue
    data_by_layer[layer] = data
    ids = [r.get(LAYER_KEYS[layer]) for r in data]
    if any(i is None for i in ids):
        errs.append(f'{layer}: 存在缺失主键 {LAYER_KEYS[layer]} 的记录')
    dups = {k: c for k, c in Counter(ids).items() if c and c > 1}
    if dups:
        errs.append(f'{layer}: ID 重复 {dups}')
    for r in data:
        ii = r.get('item_id')
        if ii not in valid_items:
            errs.append(f"{layer}: 非法 item_id {r.get(LAYER_KEYS[layer])} -> {ii}")
        else:
            covered.add(ii)

# ENT 上限
ents = data_by_layer.get('ents', [])
for r in ents:
    n = int(r['ent_id'].split('-')[1])
    if not (3000 <= n <= 3099):
        errs.append(f"ents: {r['ent_id']} 超出 ENT-3000..ENT-3099")
for r in ents:
    ent_ids.add(r['ent_id'])
    if r['type'] not in ENTITY_TYPES: errs.append(f"ents: {r['ent_id']} type 非法 {r['type']}")
    if r['faction'] not in FACTIONS: errs.append(f"ents: {r['ent_id']} faction 非法 {r['faction']}")
    if r['confidence'] not in CONFIDENCE: errs.append(f"ents: {r['ent_id']} confidence 非法")
    for role in r['role_in_entry']:
        if role not in ('主体', '客体', '评论对象', '引用人物', '关联人物'):
            errs.append(f"ents: {r['ent_id']} role 非法 {role}")

for r in data_by_layer.get('rules', []):
    if r['category'] not in RULE_TYPES: errs.append(f"rules: {r['rule_id']} category 非法 {r['category']}")
    if r['status'] not in ACTUAL_PRACTICE: errs.append(f"rules: {r['rule_id']} status 非法 {r['status']}")
for r in data_by_layer.get('events', []):
    if 'event_id' not in r: errs.append(f"events: {r.get('evt_id')} 主键必须为 event_id")
    if r['event_type'] not in EVENT_TYPES: errs.append(f"events: {r['event_id']} event_type 非法 {r['event_type']}")
for r in data_by_layer.get('appts', []):
    if r['person'] not in ent_ids: errs.append(f"appts: {r['appt_id']} person 悬空 {r['person']}")
    if r['type'] not in APPT_STATUS: errs.append(f"appts: {r['appt_id']} type 非法 {r['type']}")
    if r['reign'] not in REIGN_FOCUS: errs.append(f"appts: {r['appt_id']} reign 非法 {r['reign']}")
for r in data_by_layer.get('rels', []):
    if r['source'] not in ent_ids: errs.append(f"rels: {r['rel_id']} source 悬空 {r['source']}")
    if r['target'] not in ent_ids: errs.append(f"rels: {r['rel_id']} target 悬空 {r['target']}")
    if r['relation'] not in RELATION_TYPES: errs.append(f"rels: {r['rel_id']} relation 非法 {r['relation']}")
    if r['direction'] not in ('单向', '双向', '未明'): errs.append(f"rels: {r['rel_id']} direction 非法")
    if r['evidence_strength'] not in ('直接表述', '推断', '旁证'): errs.append(f"rels: {r['rel_id']} evstr 非法")
for r in data_by_layer.get('cits', []):
    if r['cite_context'] not in CIT_CTX: errs.append(f"cits: {r['cit_id']} cite_context 非法 {r['cite_context']}")
for r in data_by_layer.get('opns', []):
    if r['author'] not in ent_ids: errs.append(f"opns: {r['opn_id']} author 悬空 {r['author']}")
    if r['opinion_type'] not in COMMENTARY_TYPES: errs.append(f"opns: {r['opn_id']} opinion_type 非法 {r['opinion_type']}")
    if r['tone'] not in TONES: errs.append(f"opns: {r['opn_id']} tone 非法 {r['tone']}")
    if r['firsthand_witness'] not in FIRSTHAND: errs.append(f"opns: {r['opn_id']} firsthand 非法 {r['firsthand_witness']}")
    if r['faction'] not in FACTIONS: errs.append(f"opns: {r['opn_id']} faction 非法")
for r in data_by_layer.get('mings', []):
    if r['person'] not in ent_ids: errs.append(f"mings: {r['ming_id']} person 悬空 {r['person']}")
    if r['reign'] not in REIGN_FOCUS: errs.append(f"mings: {r['ming_id']} reign 非法 {r['reign']}")
for r in data_by_layer.get('tmes', []):
    if r['reign'] not in REIGN_FOCUS: errs.append(f"tmes: {r['tme_id']} reign 非法 {r['reign']}")
    if r['era'] not in set(REIGN_ORDER.values()): errs.append(f"tmes: {r['tme_id']} era 非法 {r['era']}")
    if r['category'] not in TME_CATEGORIES: errs.append(f"tmes: {r['tme_id']} category 非法 {r['category']}")
for r in data_by_layer.get('regs', []):
    if r['type'] not in REG_CATEGORIES: errs.append(f"regs: {r['reg_id']} type 非法 {r['type']}")

missing = sorted(valid_items - covered)
if missing:
    errs.append(f'未覆盖条目: {missing}')

print('=' * 50)
print('记录数:', {l: len(d) for l, d in sorted(data_by_layer.items())})
print('条目覆盖: %d/64' % len(covered))
