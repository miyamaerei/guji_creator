def dump(layer, data):
    d = os.path.join(LAYERS, layer)
    os.makedirs(d, exist_ok=True)
    p = os.path.join(d, "{}_{}.json".format(layer, V))
    with open(p, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    return len(data)

