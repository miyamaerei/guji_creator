def assign(records, key, prefix, vol=VOL):
    for i, r in enumerate(records):
        r[key] = "%s%s-%03d" % (prefix, vol, i + 1)

assign(RULES, "rule_id", "RULE-")
assign(EVENTS, "event_id", "EVT-")
assign(APPTS, "appt_id", "APPT-")
assign(RELS, "rel_id", "REL-")
assign(CITS, "cit_id", "CIT-")
assign(OPNS, "opn_id", "OPN-")
assign(MING, "ming_id", "MING-")
assign(TMS, "tme_id", "YHB-TME-")
assign(REGS, "reg_id", "REG-")

OUT = [
    ("ents", ENTS), ("rules", RULES), ("events", EVENTS), ("appts", APPTS),
    ("rels", RELS), ("cits", CITS), ("opns", OPNS), ("mings", MING),
    ("tmes", TMS), ("regs", REGS),
]
for layer, records in OUT:
    d = os.path.join(BASE, layer)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, "%s_%s.json" % (layer, VOL))
    with open(path, "w", encoding="utf-8") as f:
        json.dump(records, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("%-6s %3d records -> %s" % (layer, len(records), path))

