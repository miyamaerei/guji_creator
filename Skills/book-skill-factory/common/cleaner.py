# -*- coding: utf-8 -*-
"""book-skill-factory common/cleaner.py

文本清洗参考模板：把解析得到的原始段落/表格还原成干净正文。
不针对任何书，只做通用清洗；书的特异噪声由 structure.json 的 omit_lines 表达。
"""

import re

_OOPS = re.compile(r"[\uE000-\uF8FF〇]")
_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def clean_text(t, strip_artifacts=True):
    """段落级通用清洗：去常见 html 残留、控制字符、规范化空白与缺字占位。"""
    t = (
        t.replace("&nbsp;", " ")
        .replace("&amp;", "&")
        .replace("<br>", "")
        .replace("</br>", "")
        .replace("<br/>", "")
        .replace("<br />", "")
        .replace("</p>", "")
        .replace("<p>", "")
        .replace("</div>", "")
        .replace("<div>", "")
        .replace("<!--", "")
        .replace("-->", "")
    )
    if strip_artifacts:
        t = _OOPS.sub("□", t)
        t = _CTRL.sub("", t)
        t = re.sub(r"[ \t　]+", " ", t)
        t = re.sub(r"\n{3,}", "\n\n", t)
        t = re.sub(r"^\s+|\s+$", "", t, flags=re.M)
    return t.strip()


def clean_table(t, strip_artifacts=True):
    """表格行通用清洗（按 | 对齐列）。"""
    t = re.sub(r"\n{2,}", "\n", t)
    t = re.sub(r"[ \t　]+", " ", t)
    t = re.sub(r"^\s+|\s+$", "", t, flags=re.M)
    t = t.strip()
    if not t:
        return ""
    if "\n" not in t:
        return "<TABLE>" + t + "</TABLE>"
    rows = t.split("\n")
    n = max(len(r.split("|")) for r in rows)
    for i, r in enumerate(rows):
        cols = r.split("|") + [""] * (n - len(r.split("|")))
        rows[i] = "|".join(c.strip() for c in cols)
    return ("<TABLE>\n" + "\n".join(rows) + "\n</TABLE>").replace("\n", " ")


def strip_export_artifacts(text):
    """去掉导出版本自带的非正文注记（整行噪声）。"""
    out = []
    for line in text.split("\n"):
        s = line.strip()
        if re.match(
            r"^Document generated by .*?(Anna'?s Archive|z-lib|libgen)", s, re.I
        ):
            continue
        if re.match(r"^(Generated|Downloaded|Saved) with", s, re.I):
            continue
        out.append(line)
    return "\n".join(out)


def should_drop_line(line, omit_patterns):
    """按 structure.json 的 omit_lines 正则判断某整行是否丢弃。"""
    for p in omit_patterns or []:
        try:
            if re.search(p, line):
                return True
        except re.error:
            continue
    return False
