"""book-skill-factory generate.py - 生成书实例的「skills 工厂」入口

定位：这是一个工厂，不是任何一本书的实例。
本文件与 common/、templates/ 全部是参考实现，不针对任何具体书写死解析逻辑；
每一本书的结构规则由 HEURISTICS.md 六组启发式问题的答案决定，答案被翻译
成书实例自己的 structure.json（schema 见 common/schemas.py）。

三种调用模式（都绕过「为书写死代码」）：
  1) 交互问询（默认）：逐题按 HEURISTICS.md 六组问题提问 -> 组装 structure.json
  2) --answers <file>  ：把问询答案预先写成 JSON（可回放/批处理），直接翻译
  3) --no-interactive  ：无 TTY 或主动跳过问询，按问题默认参考答案自动落盘
  4) --config <file>   ：已有 structure.json，直接渲染书实例（跳过问询）

产物（每个书实例）：
  book-<slug>/SKILL.md          实例元数据与用法
  book-<slug>/structure.json    结构规则唯一真源（问询答案的机器形态）
  book-<slug>/scripts/extract.py  薄壳：从 book-skill-factory/common 读取参考引擎（零复制）

用法示例:
  python generate.py --book xxx.json
  python generate.py --book xxx.json --no-interactive
  python generate.py --book xxx.json --answers answers.json
  python generate.py --config book-xxx/structure.json
"""

