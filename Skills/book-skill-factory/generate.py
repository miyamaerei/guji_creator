def parse_value(raw, spec):
    """把用户输入按问题类型解析为答案值。"""
    kind = spec["kind"]
    if kind == "bool":
        if isinstance(raw, bool):
            return raw
        return str(raw).strip().lower() in ("y", "yes", "true", "1")
    if kind == "list":
        if isinstance(raw, list):
            return [x.strip() for x in raw if str(x).strip()]
        return [x.strip() for x in str(raw).replace("\n", ",").split(",") if x.strip()]
    if kind == "choice":
        val = str(raw).strip()
        return val if val in spec["choices"] else spec["default"]
    return str(raw).strip()


def ask_interactive(specs):
    """交互问询：逐题提问，回车取默认；非 TTY 或 EOF 时退回参考答案。"""
    print("=== book-skill-factory 问询向导（HEURISTICS.md 六组问题）===")
    print(
        "每条回答回车=采用默认；回答 REGEX: 开头表示直接给正则，否则按样例行自动转义。"
    )
    answers = {}
    for spec in specs:
        if "group" in spec:
            print("\n[%s]" % spec["group"])
        print(spec["question"])
        try:
            line = input("> ").strip()
        except (EOFError, KeyboardInterrupt):
            line = ""
        answers[spec["key"]] = parse_value(line, spec)
    return answers


def reference_answers(specs, overrides=None):
    """参考答案：无问询时使用每组问题的默认值，可被 --answers 覆盖。"""
    answers = {spec["key"]: spec["default"] for spec in specs}
    if overrides:
        answers.update(overrides)
    return answers


def load_answers_file(path):
    with open(path, "rb") as f:
        raw = f.read()
    for enc in ("utf-8-sig", "utf-8", "gb18030"):
        try:
            return json.loads(raw.decode(enc))
        except (UnicodeDecodeError, json.JSONDecodeError):
            continue
    raise ValueError("无法解析答案文件: %s" % path)


# ---------------------------------------------------------------------------
# 答案 -> structure.json 翻译（表达方式：样例行自动转义 / REGEX: 前缀直通）
# ---------------------------------------------------------------------------
def to_regex(sample):
    """样例行 -> 字面转义正则；REGEX: 前缀 -> 原样当正则。空串 -> 正则('')。"""
    s = (sample or "").strip()
    if not s:
        return ""
    if s.startswith("REGEX:"):
        return s[len("REGEX:") :]
    return re.escape(s)


_CN_NUM = r"[一二三四五六七八九十百零〇0-9]+"


def _volume_patterns(answers):
    """卷标记正则：按问询的形态生成对应编号正则（参考模板，形态见 Q3）。

    h=井号标题(# 卷一) c=HTML注释(<!-- **卷三** -->) p=纯文本行(卷一) r=自定义正则
    """
    form = answers.get("volumes.form", "h")
    if form == "r":
        pat = (answers.get("volumes.pattern") or "").strip()
        return [pat] if pat else []
    form_patterns = {
        "h": r"^\s*#\s*卷%s\s*$" % _CN_NUM,
        "c": r"<!--\s*\*\*卷%s\*\*\s*-->" % _CN_NUM,
        "p": r"^\s*卷%s\s*$" % _CN_NUM,
    }
    return [form_patterns.get(form, form_patterns["h"])]


def answers_to_structure(answers):
    cfg = schemas.default_layout()

    toc = {}
    if answers.get("toc.exists", True):
        toc = {
            "pattern": to_regex(answers.get("toc.anchor")),
            "end_exclusive": to_regex(answers.get("toc.end")),
        }
    cfg["toc_anchor"] = toc

    body = {"pattern": to_regex(answers.get("body.anchor"))}
    cfg["body_anchor"] = body if body["pattern"] else {}

    kind = answers.get("volumes.kind", "regex_match")
    if kind == "fixed_list":
        cfg["volume_pattern"] = {
            "kind": "fixed_list",
            "pattern": [],
            "names": [n for n in answers.get("volumes.names", [])],
        }
    elif kind == "none":
        cfg["volume_pattern"] = {"kind": "none", "pattern": [], "names": []}
    else:
        cfg["volume_pattern"] = {
            "kind": "regex_match",
            "pattern": _volume_patterns(answers),
            "names": [],
        }

    hk = answers.get("heading.kind", "h2")
    cfg["heading_kind"] = hk
    if hk == "plain":
        cfg["heading_pattern"] = answers.get("heading.pattern") or r"^\S.*$"
    elif hk == "none":
        cfg["heading_pattern"] = ""

    cfg["keep_pages"] = bool(answers.get("paragraph.keep_pages", False))
    cfg["omit_lines"] = [p for p in answers.get("noise.omit", []) if p]
    cfg["strip_artifacts"] = bool(answers.get("noise.strip_artifacts", True))
    return cfg


# ---------------------------------------------------------------------------
# 渲染书实例（模板驱动，模板占位符 {{title}}/{{slug}}/{{book_path}}/{{factory_rel}}）
# ---------------------------------------------------------------------------
def render_template(tpl_path, mapping):
    with open(tpl_path, "r", encoding="utf-8") as f:
        tpl = f.read()
    for k, v in mapping.items():
        tpl = tpl.replace("{{%s}}" % k, str(v))
    return tpl


def slugify(title):
    s = re.sub(r"[\\/:*?\"<>|\s()（）\[\]【】《》,，。.;；:：!！?？]", "", title)
    return s[:40] or "book"


def render_instance(out_dir, slug, title, book_path, kind, cfg):
    """写 book-<slug>/ 下的 SKILL.md / scripts/extract.py / structure.json。"""
    inst = os.path.join(out_dir, "book-%s" % slug)
    scripts = os.path.join(inst, "scripts")
    os.makedirs(scripts, exist_ok=True)

    mapping = {
        "title": title,
        "slug": slug,
        "book_path": book_path,
        "book_kind": kind,
    }

    with open(os.path.join(inst, "SKILL.md"), "w", encoding="utf-8") as f:
        f.write(render_template(os.path.join(TEMPLATES_DIR, "SKILL.md.tpl"), mapping))
    with open(os.path.join(scripts, "extract.py"), "w", encoding="utf-8") as f:
        f.write(render_template(os.path.join(TEMPLATES_DIR, "extract.py.tpl"), mapping))
    with open(os.path.join(inst, "structure.json"), "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=2)
    return inst


