# 主流程
# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(
        description="book-skill-factory: 问询驱动生成书实例技能"
    )
    ap.add_argument("--book", help="源书路径 (txt/md/json/epub)")
    ap.add_argument(
        "--kind", choices=["auto", "txt", "md", "json", "epub"], default="auto"
    )
    ap.add_argument("--title", help="书名（默认取文件名）")
    ap.add_argument("--slug", help="实例目录名 book-<slug>（默认由书名生成）")
    ap.add_argument(
        "--out",
        default=os.path.dirname(FACTORY_DIR),
        help="实例输出目录（默认与工厂同级，即技能安装目录）",
    )
    ap.add_argument("--answers", help="问询答案 JSON 文件（键见 QUESTION_SPECS）")
    ap.add_argument("--config", help="已有 structure.json，跳过问询并覆盖式渲染实例")
    ap.add_argument(
        "--no-interactive", action="store_true", help="跳过问询，使用参考答案"
    )
    args = ap.parse_args()

    # 模式 4: --config 直达
    if args.config:
        with open(args.config, "r", encoding="utf-8") as f:
            cfg = json.load(f)
        cfg.setdefault("source", {})
        cfg["source"]["factory_dir"] = FACTORY_DIR  # 实例运行时据此定位工厂引擎
        src = cfg["source"]
        title = args.title or src.get("title") or "unknown"
        book_path = src.get("book_path", "")
        kind = src.get("kind", "auto")
        ok, errors = schemas.validate_structure(cfg)
        if not ok:
            sys.exit("structure.json 校验失败: %s" % "; ".join(errors))
        slug = args.slug or slugify(title)
        inst = render_instance(args.out, slug, title, book_path, kind, cfg)
        print("[--config] 实例已渲染: %s" % inst)
        return

    if not args.book:
        sys.exit("需要 --book <path> 或 --config <structure.json>")

    # 读入源书（输入归一化，不解析结构）
    text = load_book(args.book, args.kind)
    title = args.title or os.path.splitext(os.path.basename(args.book))[0]

    # 收集答案：--answers > 交互问询(TTY) > 参考答案
    if args.answers:
        overrides = load_answers_file(args.answers)
        answers = reference_answers(QUESTION_SPECS, overrides=overrides)
    elif args.no_interactive or not sys.stdin.isatty():
        print("非交互模式（或 stdin 非 TTY）: 使用 HEURISTICS.md 参考答案自动落盘。")
        print("如需定制结构，请使用 --answers <file> 或 --config <structure.json>。")
        answers = reference_answers(QUESTION_SPECS)
    else:
        answers = ask_interactive(QUESTION_SPECS)

    cfg = answers_to_structure(answers)
    ok, errors = schemas.validate_structure(cfg)
    if not ok:
        sys.exit("structure.json 校验失败: %s" % "; ".join(errors))

    # 用选定结构试解析一遍，产出 stats 快照供人工核验
    result = parse_book(text, cfg)
    headings = sum(
        1 for _, evs in result["volumes"] for e in evs if e["type"] == "heading"
    )
    paragraphs = sum(
        1 for _, evs in result["volumes"] for e in evs if e["type"] == "para"
    )
    chars = sum(count_chars(evs) for _, evs in result["volumes"])
    cfg["source"] = {
        "title": title,
        "book_path": os.path.abspath(args.book),
        "kind": args.kind
        if args.kind != "auto"
        else os.path.splitext(args.book)[1].lstrip("."),
        "factory_dir": FACTORY_DIR,  # 实例运行时据此定位工厂引擎
    }
    cfg["stats"] = {
        "volumes": len(result["volumes"]),
        "headings": headings,
        "paragraphs": paragraphs,
        "chars": chars,
    }

    slug = args.slug or slugify(title)
    inst = render_instance(args.out, slug, title, args.book, args.kind, cfg)

    print("\n=== 生成完成 ===")
    print("实例目录: %s" % inst)
    print("结构配置: %s/structure.json" % inst)
    print(
        "快照统计: 卷=%d 标题=%d 段落=%d 正文字符=%d"
        % (len(result["volumes"]), headings, paragraphs, chars)
    )
    print("统计供人工核验，若不合预期请调整 --answers 后重新生成（改答案不改代码）。")
    print("提取正文: python scripts/extract.py --mode volumes|full|toc --out <目录>")


if __name__ == "__main__":
    main()
