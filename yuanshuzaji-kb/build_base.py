def norm_text(s):
    out = []
    for ch in s:
        if ch in NORM_MAP:
            out.append(NORM_MAP[ch])
        elif ch in TRAD_MAP:
            out.append(TRAD_MAP[ch])
        else:
            out.append(ch)
    return "".join(out)


def split_volume(vno):
    """切分一卷，返回 [(item_id, title, body)]"""
    fn = os.path.join(SRC_DIR, "卷%s.txt" % CN[vno - 1])
    with open(fn, encoding="utf-8") as f:
        lines = [l.rstrip("\n").rstrip("\r") for l in f]

    items = []
    seq = 0
    cur_title = None
    cur_body = []

    def flush():
        nonlocal cur_title, cur_body, seq
        if cur_title is not None:
            items.append((seq, cur_title, "".join(cur_body)))
            cur_title = None
            cur_body = []

    for ln in lines:
        s = ln.strip()
        if not s:
            continue
        if s.startswith("【卷"):   # 卷首标记行，跳过
            continue
        m = re.match(r"^[○△](.+)$", s)
        if m:
            if s in GROUP_O:
                flush()           # 分组标题：闭当前条，不入条目（卷内分区标记）
                continue
            flush()
            seq += 1
            cur_title = s
            cur_body = []
            continue
        if cur_title is None:
            # 卷首残留（自序/序言等无标题行，不含 ○/△）——按卷首序言跳过
            continue
        cur_body.append(s)
    flush()

    return [(vno, "%02d-%03d" % (vno, i + 1), t, b) for i, (_, t, b) in enumerate(items)]


def main():
    registry = {}
    total = 0
    for vno in range(1, 21):
        items = split_volume(vno)
        vol_total = len(items)
        exp = VOL_EXPECT[str(vno)]
        flag = "OK" if vol_total == exp else "!! MISMATCH"
        print("卷%d：切出 %d 条（期望 %d）%s" % (vno, vol_total, exp, flag))
        total += vol_total
        with open(os.path.join(OUT_DIR, "%02d_卷%s.txt" % (vno, CN[vno - 1])), "w", encoding="utf-8") as f:
            for i, (v, iid, title, body) in enumerate(items):
                f.write("条%d|%s|%s\n" % (i + 1, title, body))
                registry[iid] = {"original": ("%s\n%s" % (title, body)), "norm": norm_text(body)}
    with open(os.path.join(ROOT, "_item_registry.json"), "w", encoding="utf-8") as f:
        json.dump(registry, f, ensure_ascii=False, indent=1)
    print("总计：%d 条（期望 165）" % total)
    empties = [k for k, v in registry.items() if not v["norm"].strip()]
    print("空正文条目：%d %s" % (len(empties), empties))


if __name__ == "__main__":
    main()
