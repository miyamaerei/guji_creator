def check_enum(value, enum_dict, label, version):
    """校验值在枚举内；失败抛 ValueError（验证脚本与打包器共用）。"""
    if value not in enum_dict:
        raise ValueError(
            f"[{label}] 非法枚举值: {value!r}（合法: {list(enum_dict.keys())}）"
        )
    return True


def check_in_list(value, enum_list, label, version):
    """校验值在列表枚举内。"""
    if value not in enum_list:
        raise ValueError(
            f"[{label}] 非法枚举值: {value!r}（合法: {enum_list}）"
        )
    return True


